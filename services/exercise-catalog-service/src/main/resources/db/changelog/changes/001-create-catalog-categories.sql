-- Категории каталога упражнений. Физического удаления нет: записи деактивируются.
CREATE TABLE catalog_categories (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 32767),
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    version BIGINT NOT NULL CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX catalog_categories_active_order_index
    ON catalog_categories (is_active, sort_order, id);

COMMENT ON TABLE catalog_categories IS 'Категории справочника упражнений.';
