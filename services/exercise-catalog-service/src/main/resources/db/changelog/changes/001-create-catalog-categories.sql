-- Категории каталога упражнений: read-only справочник для MVP.
CREATE TABLE catalog_categories (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
        CHECK (id BETWEEN 1 AND 32767),
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    is_active BOOLEAN NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    version BIGINT NOT NULL CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE catalog_categories IS 'Категории каталога упражнений Exercise Catalog.';

-- Публичный список читается по порядку среди активных категорий.
CREATE INDEX catalog_categories_active_sort_idx
    ON catalog_categories (is_active, sort_order, id);
