-- Упражнения каталога: read-only справочник для MVP, данные поставляются миграциями.
CREATE TABLE catalog_exercises (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
        CHECK (id BETWEEN 1 AND 32767),
    category_id SMALLINT NOT NULL REFERENCES catalog_categories (id) ON DELETE RESTRICT,
    code VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    primary_metric VARCHAR(16) NOT NULL
        CHECK (primary_metric IN ('REPETITIONS', 'DURATION')),
    is_active BOOLEAN NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    version BIGINT NOT NULL CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE catalog_exercises IS 'Упражнения каталога Exercise Catalog с метрикой v1.';

-- Список упражнений категории читается по порядку среди активных записей.
CREATE INDEX catalog_exercises_category_active_sort_idx
    ON catalog_exercises (category_id, is_active, sort_order, id);
