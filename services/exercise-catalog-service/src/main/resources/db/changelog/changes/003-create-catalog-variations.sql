-- Вариации упражнений: read-only справочник; допустимая цель задаётся диапазоном и шагом.
CREATE TABLE catalog_variations (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
        CHECK (id BETWEEN 1 AND 32767),
    exercise_id SMALLINT NOT NULL REFERENCES catalog_exercises (id) ON DELETE RESTRICT,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    instructions VARCHAR(2000) NOT NULL,
    min_target BIGINT NOT NULL CHECK (min_target > 0),
    max_target BIGINT NOT NULL CHECK (max_target >= min_target),
    target_step BIGINT NOT NULL DEFAULT 1 CHECK (target_step > 0),
    is_active BOOLEAN NOT NULL,
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    version BIGINT NOT NULL CHECK (version > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE catalog_variations IS 'Вариации упражнений Exercise Catalog с границами цели.';

-- code уникален в рамках своего упражнения.
ALTER TABLE catalog_variations
    ADD CONSTRAINT catalog_variations_exercise_code_unique UNIQUE (exercise_id, code);

-- Карточка упражнения и проверка цели читают вариации по порядку среди активных.
CREATE INDEX catalog_variations_exercise_active_sort_idx
    ON catalog_variations (exercise_id, is_active, sort_order, id);
