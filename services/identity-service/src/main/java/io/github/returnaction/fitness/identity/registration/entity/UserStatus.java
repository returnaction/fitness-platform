package io.github.returnaction.fitness.identity.registration.entity;

public enum UserStatus {
    /** Пользователь создан, но ещё не активирован. */
    PENDING,

    /** Активный пользователь: ему разрешено пользоваться возможностями сервиса. */
    ACTIVE,

    /** Пользователь временно ограничен, например по решению модератора. */
    SUSPENDED,

    /** Учётная запись отключена окончательно или до явного решения администратора. */
    DISABLED
}
