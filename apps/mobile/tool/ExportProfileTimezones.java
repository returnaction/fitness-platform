import java.time.ZoneId;
import java.time.zone.ZoneRulesProvider;

// Run from the repository root with the same JDK as Accounts:
// java apps/mobile/tool/ExportProfileTimezones.java > apps/mobile/lib/features/profile/profile_timezones.dart
class ExportProfileTimezones {
    public static void main(String[] args) {
        System.out.println("// Generated by tool/ExportProfileTimezones.java; do not edit manually.");
        System.out.println("// JDK " + Runtime.version() + "; tzdb "
                + ZoneRulesProvider.getVersions("UTC").lastKey() + ".");
        System.out.println("// Refresh when the Accounts JDK timezone database changes.");
        System.out.println("const profileTimezones = <String>{");
        ZoneId.getAvailableZoneIds().stream().sorted()
                .forEach(zone -> System.out.println("  '" + zone + "',"));
        System.out.println("};");
    }
}
